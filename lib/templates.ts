/**
 * Заменить плейсхолдеры в шаблоне на актуальные значения сделки.
 */
export function applyTemplate(
  text: string,
  context: { budget?: number | null; name?: string | null; address?: string | null }
): string {
  return text
    .replace(/{budget}/g, context.budget ? new Intl.NumberFormat('ru-RU').format(context.budget) : '___')
    .replace(/{name}/g, context.name || '___')
    .replace(/{address}/g, context.address || '___')
}
